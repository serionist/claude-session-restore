const message = (line: string) => `Fix the restore band\n\nWhy it changed.\n\n${line}\nRefs #2\n`
const plain = (description: string) => `---\nname: start-work\ndescription: ${description}\n---\n`
const A = 'a'.repeat(40)
const B = 'b'.repeat(40)
const C = 'c'.repeat(40)
const ZERO = '0'.repeat(40)

/** A git repo in a temp folder, and a function that runs git in it with an invented author and no hooks. */
function newRepo(): { root: string; run: (...args: string[]) => string; done: () => void } {
  const root = mkdtempSync(join(tmpdir(), 'gate-test-'))
  const noHooks = join(root, '.no-hooks')
  mkdirSync(noHooks)
  const run = (...args: string[]) => {
    const identity = ['-c', 'user.name=Test', '-c', 'user.email=test@example.org', '-c', 'commit.gpgsign=false']
    const ran = git([...identity, '-c', `core.hooksPath=${noHooks}`, ...args], root)
    assert.equal(ran.status, 0, ran.stderr)
    return ran.stdout.trim()
  }
  run('init', '-q', '-b', 'main')

  return { root, run, done: () => rmSync(root, { recursive: true, force: true }) }
}

describe('attribution', () => {
  for (const line of REFUSED) {
    test(`finds: ${line}`, () => assert.deepEqual(attributionLines(message(line)), [line.trim()]))
  }
  for (const line of ALLOWED) {
    test(`passes: ${line}`, () => assert.deepEqual(attributionLines(message(line)), []))
  }

  test('a co-author is a tool by its address or by its name alone', () => {
    assert.equal(toolCoAuthor('Claude <claude@example.org>'), true)
    assert.equal(toolCoAuthor('Jane Doe <noreply@anthropic.com>'), true)
    assert.equal(toolCoAuthor('someone[bot] <1+someone[bot]@users.noreply.github.com>'), true)
    assert.equal(toolCoAuthor('Claude Martin <claude.martin@example.fr>'), false)
    assert.equal(toolCoAuthor('Ada Lovelace <noreply@example.org>'), false)
  })

  test('commit problems name the commit and the line', () => {
    const line = 'Co-Authored-By: Claude <noreply@anthropic.com>'
    assert.deepEqual(commitProblems([[A, message(line)]]), [`${'a'.repeat(10)}: ${line}`])
  })

  test('parseLog reads each commit and its whole message', () => {
    assert.deepEqual(parseLog(`${A}\x00One\n\nBody\n\x01\n${B}\x00Two\n\x01\n`), [
      [A, 'One\n\nBody'],
      [B, 'Two'],
    ])
  })

  test('listCommits includes merges, lists each commit once, and says what to do when the base is missing', () => {
    const { root, run, done } = newRepo()
    try {
      writeFileSync(join(root, 'a.txt'), 'a\n')
      run('add', '-A')
      run('commit', '-q', '-m', 'One')
      run('switch', '-q', '-c', 'side')
      writeFileSync(join(root, 'b.txt'), 'b\n')
      run('add', '-A')
      run('commit', '-q', '-m', 'Two')
      run('switch', '-q', 'main')
      writeFileSync(join(root, 'c.txt'), 'c\n')
      run('add', '-A')
      run('commit', '-q', '-m', 'Three')
      run('merge', '-q', '--no-ff', '-m', 'Merge side', 'side')
      const listed = listCommits(['HEAD', 'side'], root)
      assert.deepEqual(listed.commits.map(([, text]) => text).sort(), ['Merge side', 'One', 'Three', 'Two'])
      assert.match(listCommits(['origin/main..HEAD'], root).problem ?? '', /git fetch origin/)
    } finally {
      done()
    }
  })

  test('before the first push, the gate checks all of HEAD and says why; with no commit, nothing', () => {
    const { root, run, done } = newRepo()
    try {
      assert.deepEqual(cliScope('origin/main', 'HEAD', root), { ranges: [], commits: [] })
      writeFileSync(join(root, 'a.txt'), 'a\n')
      run('add', '-A')
      run('commit', '-q', '-m', 'One')
      const scope = cliScope('origin/main', 'HEAD', root)
      assert.deepEqual(scope.ranges, ['HEAD'])
      assert.equal(scope.commits.length, 1)
      assert.match(scope.note ?? '', /origin\/main doesn't exist yet/)
      assert.equal(scope.problem, undefined)
    } finally {
      done()
    }
  })
})

describe('AGENTS.md and skills', () => {
  test('AGENTS.md may have 150 lines, not 151', () => {
    assert.deepEqual(agentsMdProblems('x\n'.repeat(150)), [])
    assert.match(agentsMdProblems('x\n'.repeat(151))[0] ?? '', /151 lines/)
  })

  test('frontmatter joins a block and marks it not plain, and reads quoted values', () => {
    assert.deepEqual(frontmatter(GOOD_SKILL).get('description'), [
      'Use when someone wants to work on something: finds the issue, writes the plan.',
      false,
    ])
    assert.deepEqual(frontmatter("---\nname: 'start-work'\n---\n").get('name'), ['start-work', false])
  })

  for (const text of [
    '# no frontmatter\n',
    '---\nname: x\n',
    '---\nname: x\nname: y\n---\n',
    '---\njust words\n---\n',
  ]) {
    test(`frontmatter refuses ${JSON.stringify(text)}`, () => assert.throws(() => frontmatter(text)))
  }

  test('a good skill has no problems', () => assert.deepEqual(skillProblems('start-work', GOOD_SKILL), []))

  const cases: Array<[string, string, string, string]> = [
    ['name', 'finish-work', GOOD_SKILL, 'it must equal the folder name'],
    ['description', 'start-work', '---\nname: start-work\n---\n', 'description is missing'],
    [
      'extra key',
      'start-work',
      GOOD_SKILL.replace('name: start-work', 'name: start-work\nallowed-tools: Read'),
      'allowed-tools',
    ],
    ['trigger', 'start-work', GOOD_SKILL.replace('Use when someone', 'Helps when someone'), '"Use when ..."'],
    ['length', 'start-work', GOOD_SKILL.replace('writes the plan.', 'x'.repeat(1024)), 'keep it within 1024'],
    ['colon space', 'start-work', plain('Use when: anything'), 'write it as a >- block'],
    ['trailing colon', 'start-work', plain('Use when ready:'), 'write it as a >- block'],
    ['hash', 'start-work', plain('Use when asked #2'), 'write it as a >- block'],
    ['folder', 'Start_Work', GOOD_SKILL.replace('start-work', 'Start_Work'), 'lowercase letters, digits and hyphens'],
    ['frontmatter', 'start-work', 'no frontmatter\n', 'it does not start with a --- line'],
  ]
  for (const [id, folder, text, expected] of cases) {
    test(`skill problem: ${id}`, () => {
      const problems = skillProblems(folder, text)
      assert.equal(problems.length, 1, problems.join('\n'))
      assert.ok(problems[0]?.includes(expected), problems[0])
    })
  }
})

describe('skill links', () => {
  const LINK: [string, string, string] = ['120000', '.agents/skills/start-work', '../../.claude/skills/start-work']

  test('a link to each skill passes', () => assert.deepEqual(linkProblems([LINK], new Set(['start-work'])), []))

  const cases: Array<[string, Array<[string, string, string]>, string]> = [
    ['plain file', [['100644', LINK[1], LINK[2]]], 'is a plain file in git (mode 100644), not a link'],
    ['wrong target', [[LINK[0], LINK[1], '../../.claude/skills/finish-work']], 'points to'],
    ['missing', [], '.agents/skills/start-work is missing'],
    ['no skill', [LINK, ['120000', '.agents/skills/gone', '../../.claude/skills/gone']], 'leads to no skill'],
    ['copied folder', [['100644', '.agents/skills/start-work/SKILL.md', '']], 'holds files; it must be one link'],
  ]
  for (const [id, entries, expected] of cases) {
    test(`link problem: ${id}`, () => {
      const problems = linkProblems(entries, new Set(['start-work']))
      assert.equal(problems.length, 1, problems.join('\n'))
      assert.ok(problems[0]?.includes(expected), problems[0])
    })
  }

  test('setup link writes a symlink into the index, and the gate accepts it', () => {
    const { root, done } = newRepo()
    try {
      mkdirSync(join(root, '.claude', 'skills', 'start-work'), { recursive: true })
      writeFileSync(join(root, '.claude', 'skills', 'start-work', 'SKILL.md'), GOOD_SKILL)
      const [ok, line] = link(root, 'start-work')
      assert.ok(ok, line)
      const [mode = '', sha = '', , path = ''] = git(['ls-files', '-s', '--', '.agents/skills'], root).stdout.split(
        /\s+/,
      )
      assert.equal(mode, '120000')
      assert.equal(path, '.agents/skills/start-work')
      const target = git(['cat-file', 'blob', sha], root).stdout
      assert.deepEqual(linkProblems([[mode, path, target]], new Set(['start-work'])), [])
      const onDisk = join(root, '.agents', 'skills', 'start-work')
      assert.ok(
        lstatSync(onDisk).isSymbolicLink() || readFileSync(onDisk, 'utf8') === '../../.claude/skills/start-work',
      )
      assert.equal(link(root, 'gone')[0], false)
    } finally {
      done()
    }
  })
})

describe('the hooks', () => {
  test('hooks stored as executable pass; one added from Windows without the bit fails', () => {
    assert.deepEqual(hookProblems([['100755', '.githooks/pre-push']]), [])
    assert.deepEqual(hookProblems([['100644', '.githooks/pre-push']]), [
      '.githooks/pre-push is stored as mode 100644, so Linux and macOS skip it: git update-index --chmod=+x .githooks/pre-push',
    ])
  })

  test('commit-msg refuses attribution, accepts a clean message, and reads above the scissors line only', () => {
    const folder = mkdtempSync(join(tmpdir(), 'commit-msg-'))
    const file = join(folder, 'COMMIT_EDITMSG')
    const stderr = process.stderr.write
    process.stderr.write = () => true
    try {
      writeFileSync(file, message('Co-Authored-By: Claude <noreply@anthropic.com>'))
      assert.equal(commitMsg(file), 1)
      writeFileSync(file, message('Refs #3'))
      assert.equal(commitMsg(file), 0)
      const diff =
        '# ------------------------ >8 ------------------------\n+Co-Authored-By: Claude <noreply@anthropic.com>\n'
      writeFileSync(file, `Add the gate\n\n# On branch claude-code-session\n${diff}`)
      assert.equal(commitMsg(file), 0)
      assert.equal(messageText(`One\n${diff}`), 'One')
    } finally {
      process.stderr.write = stderr
      rmSync(folder, { recursive: true, force: true })
    }
  })

  test('pre-push reads what each ref sends', () => {
    const lines = [
      `refs/heads/a ${A} refs/heads/a ${B}`,
      `refs/heads/new ${C} refs/heads/new ${ZERO}`,
      `(delete) ${ZERO} refs/heads/gone ${A}`,
      '',
    ]
    assert.deepEqual(
      pushRanges(lines, 'origin/main', () => true),
      [
        [`${B}..${A}`, A],
        [`origin/main..${C}`, C],
      ],
    )
    assert.deepEqual(
      pushRanges([lines[0] ?? ''], 'origin/main', () => false),
      [[`origin/main..${A}`, A]],
    )
  })

  test('the working tree stands for a push only of HEAD with nothing else in it', () => {
    assert.equal(treeSkipReason([A], A, false), undefined)
    assert.match(treeSkipReason([B], A, false) ?? '', /not HEAD/)
    assert.match(treeSkipReason([A], A, true) ?? '', /changes or untracked/)
  })

  test('the AI setup files', () => {
    for (const path of ['AGENTS.md', 'plugin/CLAUDE.md', '.claude/settings.json', '.agents/skills/x', 'REVIEW.md']) {
      assert.equal(isAgentSetup(path), true, path)
    }
    for (const path of ['README.md', 'plugin/hooks/lib.ts', 'docs/REVIEW.md'])
      assert.equal(isAgentSetup(path), false, path)
  })

  test('post-checkout says nothing when no branch changed', () => {
    assert.equal(postCheckout(A, B, '0'), 0)
    assert.equal(postCheckout(A, A, '1'), 0)
    assert.equal(postCheckout(ZERO, B, '1'), 0)
  })
})

describe('pins and versions', () => {
  const have = (versions: Record<string, string>) => (name: string) => versions[name]

  test('every tool pinned exactly, locked and installed passes', () => {
    assert.deepEqual(
      dependencyProblems({ typescript: '6.0.3' }, { typescript: '6.0.3' }, have({ typescript: '6.0.3' })),
      [],
    )
  })

  test('a range, a lock that differs and a missing install each fail', () => {
    assert.match(dependencyProblems({ x: '^1.0.0' }, { x: '^1.0.0' }, have({ x: '1.0.0' }))[0] ?? '', /pin one exact/)
    assert.match(dependencyProblems({ x: '1.0.1' }, { x: '1.0.0' }, have({ x: '1.0.1' }))[0] ?? '', /npm install/)
    assert.match(dependencyProblems({ x: '1.0.0' }, { x: '1.0.0' }, have({}))[0] ?? '', /npm ci/)
    assert.match(dependencyProblems({}, { x: '1.0.0' }, have({}))[0] ?? '', /still has x/)
  })

  test("the plugin's version needs its dated CHANGELOG section", () => {
    assert.deepEqual(versionProblems('0.1.0', '## Unreleased\n\n## 0.1.0 (2026-10-28)\n'), [])
    assert.match(versionProblems('0.2.0', '## Unreleased\n\n## 0.1.0 (2026-10-28)\n')[0] ?? '', /no "## 0.2.0/)
    assert.match(versionProblems('0.2', '')[0] ?? '', /not X.Y.Z/)
  })
})
